#!/usr/bin/env node
// Regenerates src/i18n/messages/index.ts from whatever namespace JSON files
// exist under src/i18n/messages/{zh,en}/. Run after adding/removing a
// namespace file. Requires zh and en to have the exact same file set.
import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(fileURLToPath(import.meta.url));
const messagesDir = path.join(root, "..", "src", "i18n", "messages");

const zhFiles = readdirSync(path.join(messagesDir, "zh")).filter((f) => f.endsWith(".json")).sort();
const enFiles = readdirSync(path.join(messagesDir, "en")).filter((f) => f.endsWith(".json")).sort();

const zhSet = new Set(zhFiles);
const enSet = new Set(enFiles);
const missingInEn = zhFiles.filter((f) => !enSet.has(f));
const missingInZh = enFiles.filter((f) => !zhSet.has(f));
if (missingInEn.length || missingInZh.length) {
  console.error("Mismatch between zh/ and en/ namespace files:");
  if (missingInEn.length) console.error("  missing in en/:", missingInEn.join(", "));
  if (missingInZh.length) console.error("  missing in zh/:", missingInZh.join(", "));
  process.exit(1);
}

const namespaces = zhFiles.map((f) => f.replace(/\.json$/, "")).sort();

const importLines = [];
for (const ns of namespaces) importLines.push(`import ${ns}En from "./en/${ns}.json";`);
for (const ns of namespaces) importLines.push(`import ${ns}Zh from "./zh/${ns}.json";`);
importLines.sort();

const zhEntries = namespaces.map((ns) => `    ${ns}: ${ns}Zh,`).join("\n");
const enEntries = namespaces.map((ns) => `    ${ns}: ${ns}En,`).join("\n");

const content = `// AUTO-GENERATED by scripts/gen-i18n-index.mjs — do not hand-edit.
// Re-run \`node scripts/gen-i18n-index.mjs\` after adding/removing a namespace
// file under src/i18n/messages/{zh,en}/.
${importLines.join("\n")}

export const MESSAGES = {
  zh: {
${zhEntries}
  },
  en: {
${enEntries}
  },
} as const;
`;

writeFileSync(path.join(messagesDir, "index.ts"), content);
console.log(`Wrote index.ts with ${namespaces.length} namespaces.`);
